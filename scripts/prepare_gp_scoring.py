#!/usr/bin/env python3
"""Prepare a blind-scoring pack for GP evaluation.

Loads all sessions with SOAP notes, strips model identifiers, shuffles
the order, and outputs both JSON and Markdown for GP reviewers.
"""

from __future__ import annotations

import json
import random
import sys
from datetime import datetime, timezone
from pathlib import Path

from loguru import logger

# Allow imports from project root
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.clinical.session_store import SessionStore

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

SCORING_CRITERIA = {
    "clinical_accuracy": {
        "description": "Are the documented clinical findings factually correct?",
        "scale": "1 = Major inaccuracies, 5 = Completely accurate",
    },
    "completeness": {
        "description": "Is anything clinically important missing from the note?",
        "scale": "1 = Major omissions, 5 = Nothing important missing",
    },
    "structure_quality": {
        "description": "Is the note well-organised and easy to follow?",
        "scale": "1 = Poorly structured, 5 = Excellent structure",
    },
    "language_appropriateness": {
        "description": "Is the note written in UK English with a professional clinical tone?",
        "scale": "1 = Inappropriate language, 5 = Fully appropriate",
    },
    "safety_netting": {
        "description": "Are safety-netting instructions present and appropriate?",
        "scale": "1 = Missing/dangerous, 5 = Thorough and appropriate",
    },
    "coding_quality": {
        "description": "Are the SNOMED CT codes relevant and correct?",
        "scale": "1 = Incorrect/missing codes, 5 = All codes correct",
    },
    "overall_acceptability": {
        "description": "Would you sign this note as-is without edits?",
        "scale": "1 = Unacceptable, 5 = Ready to sign",
    },
}

GP_INSTRUCTIONS = """\
Thank you for taking part in this evaluation. You are reviewing clinical \
notes generated by an AI scribe from real GP consultation transcripts.

IMPORTANT:
- The notes have been randomised; you do not know which AI model produced each one.
- Please score each note independently on the criteria below (1-5 scale).
- If you spot any dangerous omissions or errors, note them under "Critical Errors".
- Mark "Would Edit" as Yes if you would need to change anything before signing off.
- Your honest, clinical judgement is what matters. There are no right answers.

Time estimate: approximately 3-5 minutes per note.
"""


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    sessions_dir = Path("data/sessions")
    output_json = Path("data/gp_scoring_pack.json")
    output_md = Path("data/gp_scoring_pack.md")

    if not sessions_dir.exists():
        logger.error(f"Sessions directory not found: {sessions_dir}")
        sys.exit(1)

    store = SessionStore(store_dir=sessions_dir)
    session_list = store.list_sessions(limit=500)
    logger.info(f"Found {len(session_list)} sessions total")

    # Filter to sessions that have a SOAP note
    notes: list[dict] = []
    for meta in session_list:
        if not meta["has_soap"]:
            continue

        full = store.load_full(meta["session_id"])
        if full is None or full.get("soap_note") is None:
            continue

        soap = full["soap_note"]
        soap_text = soap.get("raw_text", "")
        if not soap_text:
            # Reconstruct from sections if raw_text is empty
            parts = []
            for section in ("subjective", "objective", "assessment", "plan"):
                content = soap.get(section, "")
                if content:
                    parts.append(f"**{section.upper()}**\n{content}")
            soap_text = "\n\n".join(parts)

        if not soap_text.strip():
            continue

        transcript = full.get("raw_transcript", "") or full.get("diarised_transcript", "")

        notes.append({
            "id": meta["session_id"],
            "transcript_preview": transcript[:500],
            "soap_note": soap_text,
            "model_hidden": True,
            # Store model internally for later unblinding
            "_model": soap.get("model_used", "unknown"),
        })

    logger.info(f"Sessions with SOAP notes: {len(notes)}")

    if not notes:
        logger.warning("No SOAP notes found. Nothing to prepare.")
        sys.exit(0)

    # Shuffle for blind scoring
    random.shuffle(notes)

    # Assign sequential blind IDs
    for idx, note in enumerate(notes, start=1):
        note["blind_id"] = f"NOTE-{idx:03d}"

    # --------------- JSON output ---------------
    pack = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "total_notes": len(notes),
        "instructions": GP_INSTRUCTIONS,
        "scoring_criteria": SCORING_CRITERIA,
        "notes": [
            {
                "blind_id": n["blind_id"],
                "transcript_preview": n["transcript_preview"],
                "soap_note": n["soap_note"],
                "model_hidden": True,
            }
            for n in notes
        ],
        # Hidden mapping kept in a separate key so it can be stripped before
        # sending to GPs, then used later for unblinding.
        "_unblinding_map": {n["blind_id"]: {"session_id": n["id"], "model": n["_model"]} for n in notes},
    }

    output_json.parent.mkdir(parents=True, exist_ok=True)
    output_json.write_text(json.dumps(pack, indent=2))
    logger.info(f"JSON scoring pack saved: {output_json}")

    # --------------- Markdown output ---------------
    md_lines: list[str] = []
    md_lines.append("# GP Blind-Scoring Pack")
    md_lines.append("")
    md_lines.append(f"Generated: {pack['generated_at']}")
    md_lines.append(f"Total notes: {len(notes)}")
    md_lines.append("")
    md_lines.append("## Instructions")
    md_lines.append("")
    md_lines.append(GP_INSTRUCTIONS.strip())
    md_lines.append("")
    md_lines.append("## Scoring Criteria")
    md_lines.append("")
    for key, info in SCORING_CRITERIA.items():
        label = key.replace("_", " ").title()
        md_lines.append(f"### {label}")
        md_lines.append(f"{info['description']}")
        md_lines.append(f"*{info['scale']}*")
        md_lines.append("")

    md_lines.append("---")
    md_lines.append("")

    for note in notes:
        md_lines.append(f"## {note['blind_id']}")
        md_lines.append("")
        md_lines.append("### Transcript Preview")
        md_lines.append("```")
        md_lines.append(note["transcript_preview"] if note["transcript_preview"] else "(no transcript available)")
        md_lines.append("```")
        md_lines.append("")
        md_lines.append("### SOAP Note")
        md_lines.append("")
        md_lines.append(note["soap_note"])
        md_lines.append("")
        md_lines.append("### Your Scores")
        md_lines.append("")
        md_lines.append("| Criterion | Score (1-5) |")
        md_lines.append("|---|---|")
        for key in SCORING_CRITERIA:
            label = key.replace("_", " ").title()
            md_lines.append(f"| {label} | ___ |")
        md_lines.append("")
        md_lines.append("**Would you edit this note before signing?** Yes / No")
        md_lines.append("")
        md_lines.append("**Critical errors (if any):**")
        md_lines.append("")
        md_lines.append("**Comments:**")
        md_lines.append("")
        md_lines.append("---")
        md_lines.append("")

    output_md.write_text("\n".join(md_lines))
    logger.info(f"Markdown scoring pack saved: {output_md}")

    logger.info(
        f"Done. {len(notes)} notes prepared for blind GP scoring. "
        f"Send {output_md.name} to GPs (strip _unblinding_map from JSON before sharing)."
    )


if __name__ == "__main__":
    main()
